type LeafValue = { en: string; hi: string }

function isLeaf(v: unknown): v is LeafValue {
  return typeof v === "object" && v !== null && "en" in v && "hi" in v
}

function resolve(path: string): LeafValue | undefined {
  const parts = path.split(".")
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = dict
  for (const p of parts) {
    if (node == null) return undefined
    node = node[p]
  }
  return isLeaf(node) ? node : undefined
}

export function translate(lang: Lang, key: string): string {
  const leaf = resolve(key)
  if (!leaf) return key
  return leaf[lang] ?? leaf.en
}

export default dict
